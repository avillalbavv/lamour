export const requestTerms = completeTermsText;

// Preserve sample flags and stock controls; only update the original seed copy.
export function catalogPresentation(product: Product): Product {
  if (!product.is_demo) return product;
  return {
    ...product,
    sku: product.sku.replace(/^DEMO-/, "LM-"),
    description: product.description.startsWith("Producto de demostración")
      ? "Consultá disponibilidad y detalles de este producto. Confirmamos sus características, precio final y plazo antes de avanzar con tu pedido."
      : product.description.replaceAll("L’Amour Privé", "L’Amour"),
    materials: product.materials.replace("Ficha de demostración. ", ""),
  };
}

export function settingsPresentation(settings: Settings): Settings {
  return {
    ...settings,
    legal_name: settings.legal_name || "",
    tax_id: settings.tax_id || "",
    business_address: settings.business_address || "",
    privacy_text:
      settings.privacy_text.startsWith("Usamos los datos que compartís") ||
      settings.privacy_text.trim().length < 500
        ? completePrivacyText
        : settings.privacy_text.replaceAll("L’Amour Privé", "L’Amour"),
    terms_text:
      settings.terms_text.startsWith("Esta es una tienda de demostración.") ||
      settings.terms_text.trim().length < 500
        ? requestTerms
        : settings.terms_text.replaceAll("L’Amour Privé", "L’Amour"),
  };
}
